// Helper: Menghitung persentase peluang lolos dan status zona
function hitungPeluangLolos(userScore, prodiData) {
    const { skorMin, skorAman } = prodiData;
    let peluang = 0;
    let status = "";
    let statusClass = "";
    let badgeColor = "";
    let rekomendasi = "";
    let selisih = userScore - skorAman;

    if (userScore >= skorAman) {
        // ZONA AMAN (85% - 99%)
        const ekstra = Math.min(14, Math.round(((userScore - skorAman) / 50) * 10));
        peluang = 85 + ekstra;
        status = "Zona Aman (Peluang Sangat Terbuka)";
        statusClass = "text-emerald-700 bg-emerald-50 border-emerald-200";
        badgeColor = "#10b981";
        rekomendasi = `Luar biasa! Skor Anda melampaui skor aman rata-rata kelolosan (${skorAman}). Pertahankan konsistensi latihan untuk menjaga stabilitas skor saat hari H ujian.`;
    } else if (userScore >= skorMin) {
        // ZONA KOMPETITIF (55% - 84%)
        const rasio = (userScore - skorMin) / (skorAman - skorMin);
        peluang = Math.round(55 + (rasio * 29));
        status = "Zona Kompetitif (Bersaing Ketat)";
        statusClass = "text-amber-800 bg-amber-50 border-amber-200";
        badgeColor = "#f59e0b";
        const butuh = skorAman - userScore;
        rekomendasi = `Skor Anda sudah masuk rentang batas minimum (${skorMin}), namun masih butuh sekitar +${butuh} poin lagi untuk mengamankan posisi dari persaingan pendaftar lain.`;
    } else {
        // ZONA PERJUANGAN (< 55%)
        const selisihBawah = skorMin - userScore;
        peluang = Math.max(10, Math.round(50 - (selisihBawah * 0.4)));
        status = "Zona Perjuangan (Butuh Peningkatan)";
        statusClass = "text-rose-700 bg-rose-50 border-rose-200";
        badgeColor = "#ef4444";
        const butuhMin = skorMin - userScore;
        rekomendasi = `Anda butuh peningkatan sekitar +${butuhMin} poin untuk mencapai batas kelolosan minimum (${skorMin}). Kuasai konsep-konsep kunci dengan latihan bertingkat.`;
    }

    return {
        peluang: Math.min(99, Math.max(10, peluang)),
        status,
        statusClass,
        badgeColor,
        rekomendasi,
        selisih
    };
}

